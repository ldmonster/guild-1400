// gilde.exe 0x434D0C — VIBE_Render_DrawGlyph
//   unsigned int __usercall(u8 ch@al, int x@edx, int color@ecx, int y@ebx)
//
// Original (Hex-Rays):
//   v5 = &unk_62D59C + 7 * byte_75FB50[a1];       // 7-byte glyph row block
//   result = a2 + 5;                              // x + 5
//   if (a2 + 5 <= dword_7626E0) {                 // clip: right edge <= width
//     result = a4 + 7;                            // y + 7
//     if (a4 + 7 <= cy) {                         // clip: bottom edge <= height
//       result = dword_762714;                    // depth
//       v7 = dword_7626F4*a2 + dword_7626FC*a4 + dword_7626F0;  // byte addr of(x,y)
//       if (depth >= 16) {
//         if (depth <= 16) { ...16bpp row loop, *WORD = a3... }
//         else if (depth == 32) { ...32bpp row loop, *DWORD = a3... }
//       }
//     }
//   }
//   return result;
//
// Both inner loops are identical except the destination element width and the
// address advance v7 += dword_7626FC (one row pitch in BYTES) each of 7 rows;
// across the 5 columns the mask starts at 16 and halves, writing `color` where set.
// We keep the original's exact return-value contract (the failing extent or depth).
u32 DrawGlyph(u8 ch, int x, int color, int y, const u8* glyphMap,
              const PresentGlobals& g) {
    const u8* glyph = kBuiltinFontBitmap + 7 * glyphMap[ch];

    // Clip against the framebuffer extents (width = dword_7626E0 = dibStride,
    // height = cy = screenHeight). The original compares the unsigned extent.
    u32 right = static_cast<u32>(x + 5);
    if (right > static_cast<u32>(g.dibStride))
        return right;
    u32 bottom = static_cast<u32>(y + 7);
    if (bottom > static_cast<u32>(g.screenHeight))
        return bottom;

    u32 depth = static_cast<u32>(g.lockBitDepth);    // dword_762714
    // Byte address of the (x,y) pixel:  pitchExtra*x + pitchBytes*y + base.
    std::uintptr_t rowAddr = g.targetBase
        + static_cast<std::uintptr_t>(static_cast<std::intptr_t>(g.pitchExtra) * x)
        + static_cast<std::uintptr_t>(static_cast<std::intptr_t>(g.pitchBytes) * y);

    if (depth < 16)
        return depth;

    if (depth <= 16) {                               // 16bpp path
        for (int row = 0; row < 7; ++row) {
            u16* dst = reinterpret_cast<u16*>(rowAddr);
            unsigned mask = 16;                      // column 0 == leftmost
            u8 bits = glyph[row];
            for (int col = 0; col < 5; ++col) {
                if ((mask & bits) != 0)
                    *dst = static_cast<u16>(color);
                mask >>= 1;
                ++dst;
            }
            rowAddr += static_cast<std::uintptr_t>(
                static_cast<std::intptr_t>(g.pitchBytes));
        }
    } else if (depth == 32) {                        // 32bpp path
        for (int row = 0; row < 7; ++row) {
            u32* dst = reinterpret_cast<u32*>(rowAddr);
            unsigned mask = 16;
            u8 bits = glyph[row];
            for (int col = 0; col < 5; ++col) {
                if ((mask & bits) != 0)
                    *dst = static_cast<u32>(color);
                mask >>= 1;
                ++dst;
            }
            rowAddr += static_cast<std::uintptr_t>(
                static_cast<std::intptr_t>(g.pitchBytes));
        }
    }
    return depth;
}

// gilde.exe 0x434E18 — VIBE_Render_DrawText
//   char __userpurge(int x@eax, int y@edx, u8 *text@ebx, u8 r, u8 b)  [g@cl implied]
//
// Original (Hex-Rays):
//   if (!VIBE_Render_AcquireBackBuffer()) return ...;       // back-buffer lock
//   color = (r >> rPrec << gPos?...) | ...;                 // == PackColor(r,g,b)
//   v9 = text;
//   if (*text) do {
//       v7 = *v9;
//       if (*v9 != 32) v7 = VIBE_Render_DrawGlyph(*v9, x, color, y);
//       v10 = *++v9; x += 6;
//   } while (v10);
//   if (dword_7626F0) { ...inlined VIBE_Render_UnlockBackBuffer... }
//   return v7;
//
// The pack expression maps the input bytes to (g=greenByte, r=redByte, b=blueByte)
// exactly as PackColor(fmt, r, g, b) (see render/colorformat.cpp); we reuse it.
// AcquireBackBuffer / UnlockBackBuffer are the present-state helpers in
// render/surface_present.cpp; both route the DDraw lock/unlock through the shim.
u8 DrawText(int x, int y, const u8* text, u8 r, u8 g_, u8 b,
            const u8* glyphMap, PresentGlobals& g, const ColorFormat& fmt) {
    if (!AcquireBackBuffer(g))
        return 0;

    int color = static_cast<int>(PackColor(fmt, r, g_, b));

    u8 result = 0;
    const u8* p = text;
    if (*p) {
        u8 next;
        do {
            result = *p;
            if (*p != 32)
                result = static_cast<u8>(DrawGlyph(*p, x, color, y, glyphMap, g));
            next = *++p;
            x += 6;
        } while (next);
    }

    // Inlined VIBE_Render_UnlockBackBuffer tail (release the lock for this mode).
    if (g.targetBase)
        result = static_cast<u8>(UnlockBackBuffer(g, result));

    return result;
}

