// flt_62675C @0x62675C == 0x38000100. RandNext()*kRandFloatScale maps the LCG's
// [0,32767] output into ~[0,1) exactly as VIBE_Math_RandomFloatScaled does.
const double kRandFloatScale = []() {
    u32 bits = 0x38000100u;
    float f;
    std::memcpy(&f, &bits, sizeof(f));
    return static_cast<double>(f);
}();

// flt_61E588 @0x61E588 == 0x3c23d70a == 0.01f, the per-unit wanted-level scalar.
static const double kWantedScalar = []() {
    u32 bits = 0x3c23d70au;
    float f;
    std::memcpy(&f, &bits, sizeof(f));
    return static_cast<double>(f);
}();

