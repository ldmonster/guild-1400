LawRecord g_lawTable[kLawCount];

void LawTableResetDefaults() {
    std::memcpy(g_lawTable, kLawTableDefault, sizeof(g_lawTable));
}

// One-time loader so g_lawTable mirrors the binary's static .data contents from
// program start (the original is initialized data, not constructed at runtime).
namespace {
struct LawTableInit {
    LawTableInit() { LawTableResetDefaults(); }
} g_lawTableInit;
} // namespace

// gilde.exe 0x4c244c — VIBE_Gesetz_GetRecord  (al=id, edx=out).
int GesetzGetRecord(u8 id, LawRecord* out) {
    if (id >= kLawCount)
        return 0;
    std::memcpy(out, &g_lawTable[id], sizeof(LawRecord)); // qmemcpy(a2, .., 0x24)
    return 1;
}

double GesetzComputeMaxWantedLevelFromSum(int guardStationSum) {
    // Original: per-building loop tracks max workstation-cat-10 sum; a building
    // whose sum == 75 short-circuits to 0.75, otherwise level = maxSum * 0.01.
    if (guardStationSum == 75)
        return 0.75;
    return static_cast<double>(guardStationSum) * kWantedScalar;
}

// --- hooks (model the building scan + RNG the original embeds) --------------
namespace {
int DefaultGuardStationSum(i32 /*perpId*/) { return 0; }
double DefaultRandomFloat() {
    // VIBE_Math_RandomFloatScaled: (double)(int)RandNext() * flt_62675C
    return static_cast<double>(guild::crt::RandNext()) * kRandFloatScale;
}
GuardStationSumFn g_guardFn = &DefaultGuardStationSum;
RandomFloatFn     g_randFn  = &DefaultRandomFloat;
} // namespace

void GesetzSetGuardStationSumFn(GuardStationSumFn fn) {
    g_guardFn = fn ? fn : &DefaultGuardStationSum;
}
void GesetzSetRandomFloatFn(RandomFloatFn fn) {
    g_randFn = fn ? fn : &DefaultRandomFloat;
}

// gilde.exe 0x4c2c5c — VIBE_Gesetz_EvaluateViolation.
int GesetzEvaluateViolation(u8 lawId, int value, i32 victimId, i32 perpetratorId,
                            int extra, PendingCrime* out) {
    if (lawId >= kLawCount)
        return kViolationBadId;

    LawRecord rec;
    std::memcpy(&rec, &g_lawTable[lawId], sizeof(rec));

    // The original probes Person/GameObject lookups here purely for side state;
    // they do not affect the branch outcome, so the lookups are elided.

    bool violation;
    switch (rec.op) {
    case kLawOpEqual:        violation = (value == rec.threshold); break;
    case kLawOpNotEqual:     violation = (value != rec.threshold); break;
    case kLawOpLess:         violation = !(value <  rec.threshold); break;
    case kLawOpLessEqual:    violation = !(value <= rec.threshold); break;
    case kLawOpGreater:      violation = !(value >  rec.threshold); break;
    case kLawOpGreaterEqual: violation = !(value >= rec.threshold); break;
    case kLawOpSpecial:
        // case 7: caught unless (value==threshold || threshold==2).
        violation = !(value == rec.threshold || rec.threshold == 2);
        break;
    default:
        // default: v24 is 0 (never set), so the original falls through to the
        // "no violation" return (-1). v24 is only ever 0 in this port.
        return kViolationNoMatch;
    }

    if (!violation)
        return kViolationNoMatch;

    // Violation tripped -> roll against the perpetrator's max wanted level.
    double maxWanted = GesetzComputeMaxWantedLevelFromSum(g_guardFn(perpetratorId));
    if (g_randFn() >= maxWanted) {
        // Caught: the original packs a crime record and queues command 34.
        if (out) {
            out->perpetrator = perpetratorId;
            out->victim      = victimId;
            out->lawType     = rec.id;
            out->penalty     = rec.penalty;
            out->extra       = extra;
            out->value       = value;
        }
        return kViolationQueued;
    }
    // Escaped the wanted-level roll.
    return kViolationEscaped;
}

