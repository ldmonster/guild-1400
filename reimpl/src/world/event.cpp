void EventTableReset() {
    for (int i = 0; i < kEventTableCapacity; ++i) {
        std::memset(&g_eventTable[i], 0, sizeof(EventDesc));
        g_eventTable[i].category = 0xFF;  // free sentinel
    }
    g_eventTableCount = 0;
    g_missionLcgState = 0;
}

void EventTableLoadDefault() {
    EventTableReset();
    std::memcpy(g_eventTable, kDefaultImage, sizeof(kDefaultImage));
    g_eventTableCount = 48;  // dword_5383F0 == 0x30
}

// gilde.exe 0x538550 — VIBE_GesetzTable_CountByType.
int EventTableCountByCategory(u8 category) {
    if (category > kEventMaxCategory)  // a1 > 5u -> -1
        return -1;
    int count = 0;
    for (int i = 0; i < g_eventTableCount; ++i) {
        // *(int*)((char*)&dword_63CD48[v3] + 2) >> 24 == byte at record+5.
        if (g_eventTable[i].category == category)
            ++count;
    }
    return count;
}

// gilde.exe 0x5385b0 — VIBE_Mission_FindByType (cursor==0 form).
int EventTableFindByCategory(u8 category) {
    if (g_eventTableCount <= 0)
        return -1;
    for (int i = 0; i < g_eventTableCount; ++i) {
        if (g_eventTable[i].category == category)
            return i;
    }
    return -1;
}

// gilde.exe 0x538680 — VIBE_Mission_PickRandomByType.
int EventPickRandomByCategory(u8 category) {
    int count = EventTableCountByCategory(category);
    if (count <= 0)                       // v2 <= 0 -> return -1
        return -1;
    // dword_122F49C = 1103515245 * dword_122F49C + 12345  (32-bit wraparound).
    g_missionLcgState = 1103515245u * g_missionLcgState + 12345u;
    // v3 = HIWORD(state) % 0x7FFF % count.
    int pick = static_cast<int>(((g_missionLcgState >> 16) % 0x7FFFu) % static_cast<u32>(count));
    int seen = 0;
    if (g_eventTableCount <= 0)
        return -1;
    for (int i = 0; i < g_eventTableCount; ++i) {
        if (g_eventTable[i].category == category)
            ++seen;
        if (seen > pick)
            return g_eventTable[i].value;  // byte_63CD4C[24*i] == record+4
    }
    return -1;
}

