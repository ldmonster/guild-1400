// ---------------------------------------------------------------------------
// Runtime locale flags (dword_1452BBC, dword_145A3C4). The static image and every
// observed call run in the C locale, so the defaults reproduce the binary exactly.
// ---------------------------------------------------------------------------
namespace {
bool g_mbcsCpActive = false; // dword_1452BBC > 1
int  g_caseCodePage = 0;     // dword_145A3C4
} // namespace

bool MbcsCodePageActive() { return g_mbcsCpActive; }
void SetMbcsCodePageActive(bool active) { g_mbcsCpActive = active; }
int  CaseCodePage() { return g_caseCodePage; }
void SetCaseCodePage(int cp) { g_caseCodePage = cp; }

// gilde.exe 0x1421c9b — VIBE_Crt_CharTypeQuery
int CharTypeQuery(int ch, int mask) {
    // Original: if ((unsigned)(a1+1) <= 0x100) return mask & (u16)kPctype[a1];
    // i.e. single-byte fast path for ch in -1..0xFF (the -1/EOF slot reads index 0
    // in MSVC; our callers only pass 0..0xFF).
    if (static_cast<unsigned>(ch + 1) <= 0x100u)
        return mask & static_cast<u16>(kPctype[ch & 0xFF]);
    // Multibyte (two-byte) path: only reachable with an active MBCS code page; it
    // converts the pair via VIBE_Locale_MultiByteToWideAdapter. Deferred to the
    // Locale agent — see ctype.h. LOG and bail in the unsupported case.
    std::abort();
}

// gilde.exe 0x60b4c0 — VIBE_Crt_DigitValue
int DigitValue(u8 c) {
    if (c >= 0x30u && c <= 0x39u)        // '0'..'9'
        return c - 48;
    u8 lc = static_cast<u8>(ToLowerAscii(c));
    if (lc >= 0x61u && lc <= 0x7Au)      // 'a'..'z'  (the original splits this into
        return lc - 87;                  // three identical ranges; behaviour is one
    return 37;                           // contiguous a..z mapping to 10..35)
}

// gilde.exe 0x5f0c00 — VIBE_Util_ToLower
int ToLowerAscii(int c) {
    if (c >= 65 && c <= 90)
        return c + 32;
    return c;
}

// gilde.exe 0x5ea650 — VIBE_Util_CharToUpper
int ToUpperAscii(int c) {
    if (c >= 97 && c <= 122)
        return c - 32;
    return c;
}

// gilde.exe 0x1425fd1 — VIBE_Locale_ToUpper
int LocaleToUpper(int c) {
    if (CaseCodePage()) {
        // MBCS wide-case path (VIBE_Locale_MultiByteToWide). Deferred — never taken
        // in the C locale. LOG and bail if reached.
        std::abort();
    }
    if (c >= 97 && c <= 122)
        return c - 32;
    return c;
}

// gilde.exe 0x1426d1e — VIBE_Locale_ToLower
int LocaleToLower(int c) {
    if (CaseCodePage()) {
        std::abort(); // deferred MBCS path; see LocaleToUpper.
    }
    if (c >= 65 && c <= 90)
        return c + 32;
    return c;
}

